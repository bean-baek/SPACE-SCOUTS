// Regenerates public/images/community/bg_character_fill.svg.
//
// bg_character_mission_report.svg draws the mission-report character as an unfilled
// blue outline; Group.svg is that same character filled lime. Rather than positioning
// the fill with CSS (which would need mixed-unit calc and could drift as the board
// resizes), this pads Group.svg into the decor's own 374x228 viewBox at the outline's
// position. Both files then render into one identical CSS box and stay registered at
// every screen size.
//
// The offset is measured, not eyeballed: the union bounding box of the 8
// stroke="#3A39FF" paths in the decor is 123.69x151.52 at (128, 75) — Group.svg is
// 124x152, a 1:1 export of the same shape.
//
// Run: node scripts/build-decor-fill.mjs

import { readFileSync, writeFileSync } from "node:fs";

const DIR = "public/images/community";
const OFFSET = { x: 128, y: 75 };
const DECOR_BOX = { w: 374, h: 228 };

const src = readFileSync(`${DIR}/Group.svg`, "utf8");
const inner = src
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .trim();

const out = `<!-- GENERATED by scripts/build-decor-fill.mjs — do not edit by hand.
     Lime fill for the character that bg_character_mission_report.svg draws as a blue
     outline. Group.svg (124x152) padded into that file's 374x228 viewBox at the
     outline's measured position (${OFFSET.x},${OFFSET.y}), so both images share one CSS box. -->
<svg width="${DECOR_BOX.w}" height="${DECOR_BOX.h}" viewBox="0 0 ${DECOR_BOX.w} ${DECOR_BOX.h}" fill="none" xmlns="http://www.w3.org/2000/svg">
<g transform="translate(${OFFSET.x} ${OFFSET.y})">
${inner}
</g>
</svg>
`;

writeFileSync(`${DIR}/bg_character_fill.svg`, out);
console.log(`wrote ${DIR}/bg_character_fill.svg (${out.length} bytes)`);
